        public void Start()
        {
            // VRChat derives the Use tooltip/outline from this runtime flag.
            // Keep it on the receiver itself so all 361 UGUI targets share the
            // same disabled-interaction contract.
            DisableInteractive=true;
        }

        public void ClickLocation(int loc)
        {
            if(game==null||loc<0||loc>=GoGame.AREA)return;
            clickEvents++;lastClickedLocation=loc;
            // Preserve the existing cell's legal feedback and authoritative
            // TryPlay seat/match/AI/ownership validation.
            bool legal=game.IsLegalMove(loc);
            if(!legal){if(view!=null)view.SetHoverLocation(loc,false);return;}
            if(game.TryPlay(loc)&&view!=null)view.ClearHover();
        }

        public void HoverLocation(int loc)
        {
            if(game==null||view==null||loc<0||loc>=GoGame.AREA)return;
            float startedAt=Time.realtimeSinceStartup;
            bool legal=game.IsLegalMove(loc);
            view.RecordHoverLegalQuery((Time.realtimeSinceStartup-startedAt)*1000f);
            view.SetHoverLocation(loc,legal);
        }

        public void ExitLocation(int loc)
        {
            if(view!=null&&view.hoverLocation==loc)view.ClearHover();
        }

